"""Generate the Layer-1 (EU NPL template) migration from the field catalogue.

Never edit the generated migration by hand: change this script and regenerate. CI regenerates
and fails on any diff.

Usage (from repo root):
    python3 -I tools/eba_catalogue/gen_sql.py .
"""

from __future__ import annotations

import csv
import re
import sys
from pathlib import Path

ROOT = Path(sys.argv[1]) if len(sys.argv) > 1 else Path.cwd()
CATALOGUE = ROOT / "docs/reference/eba_field_catalogue.csv"
OUT = ROOT / "supabase/migrations/20261108110100_eba_layer1.sql"

SQL_TYPES = {
    "Alphanumeric": "text",
    "Choice": "text",
    "Unspecified": "text",
    "Number": "numeric(20, 2)",
    "Percentage": "numeric(20, 6)",
    "Date": "date",
    "Boolean": "boolean",
}

# Template 2 relationship tables and the fields each one uses (Regulation 2023/2083, Annex I,
# Templates 2.1 to 2.4).
T2_TABLES = {
    "t2_1_borrower_loan": ("Template 2.1: relationship borrower - loan", ["2.00", "2.01"]),
    "t2_2_mortgage_loan_protection": (
        "Template 2.2: relationship mortgage loan - protection",
        ["2.01", "2.02", "2.03"],
    ),
    "t2_3_loan_protection": (
        "Template 2.3: relationship loan other than mortgage loan - protection",
        ["2.01", "2.03"],
    ),
    "t2_4_protection_provider": (
        "Template 2.4: relationship guarantor - guarantee",
        ["2.00", "2.03"],
    ),
}

SIMPLE_TABLES = {
    "T1": ("t1_counterparty", "Template 1: counterparty"),
    "T3": ("t3_loan", "Template 3: loan"),
    "T4.1": ("t4_1_protection", "Template 4.1: collateral, guarantee and enforcement"),
    "T4.2": ("t4_2_mortgage", "Template 4.2: mortgage guarantee"),
    "T5": ("t5_collection", "Template 5: historical collection of repayments (one row per month)"),
}


def column_name(field_id: str, name: str) -> str:
    slug = re.sub(r"[^a-z0-9]+", "_", name.lower()).strip("_")
    return f"f{field_id.replace('.', '_')}_{slug}"[:63].rstrip("_")


def quote(value: str) -> str:
    return "'" + value.replace("'", "''") + "'"


def common_columns() -> list[str]:
    return [
        "  id uuid primary key default gen_random_uuid()",
        "  organization_id uuid not null references public.organization (id)",
        "  boarding_batch_id uuid not null",
        "  source_row integer not null check (source_row > 0)",
        "  created_at timestamptz not null default now()",
    ]


def table_sql(table: str, title: str, fields: list[dict[str, str]], extra: list[str]) -> list[str]:
    cols = common_columns() + extra
    for f in fields:
        cols.append(f"  {column_name(f['field_id'], f['field_name'])} {SQL_TYPES[f['data_type']]}")
    out = [f"create table eba.{table} (", ",\n".join(cols), ");"]
    out.append(f"comment on table eba.{table} is {quote(title + ' (Regulation (EU) 2023/2083, Annex I)')};")
    out.append(f"create index {table}_batch_idx on eba.{table} (boarding_batch_id);")
    out.append(f"alter table eba.{table} enable row level security;")
    for f in fields:
        out.append(
            f"comment on column eba.{table}.{column_name(f['field_id'], f['field_name'])} is "
            f"{quote(f['field_id'] + ' ' + f['field_name'])};"
        )
    out.append("")
    return out


def main() -> None:
    rows = list(csv.DictReader(CATALOGUE.open(encoding="utf-8")))
    by_id = {r["field_id"]: r for r in rows}
    lines = [
        "-- GENERATED by tools/eba_catalogue/gen_sql.py from docs/reference/eba_field_catalogue.csv.",
        "-- Do not edit by hand. Layer 1: EU NPL transaction data templates (Regulation (EU) 2023/2083).",
        "-- One typed column per catalogue field; staging for boarding and the source for tape exports.",
        "",
    ]
    for tid, (table, title) in SIMPLE_TABLES.items():
        fields = [r for r in rows if r["template_id"] == tid]
        extra = ["  month_offset integer not null check (month_offset > 0)"] if tid == "T5" else []
        if tid == "T5":
            title += "; month_offset 1 = the month before the cut-off date"
        lines += table_sql(table, title, fields, extra)
    for table, (title, ids) in T2_TABLES.items():
        lines += table_sql(table, title, [by_id[i] for i in ids], [])

    lines += [
        "create table eba.field_catalogue (",
        "  field_id text primary key,",
        "  template_id text not null,",
        "  field_name text not null,",
        "  data_type text not null,",
        "  column_name text not null,",
        "  mandatory boolean not null,",
        "  borrower_type text not null,",
        "  loan_type text not null,",
        "  allowed_values text[] not null default '{}',",
        "  code_list text",
        ");",
        "alter table eba.field_catalogue enable row level security;",
        "comment on table eba.field_catalogue is "
        "'EU NPL template fields (Regulation (EU) 2023/2083, Annex II); see docs/reference/SOURCES.md';",
        "insert into eba.field_catalogue (field_id, template_id, field_name, data_type, column_name, "
        "mandatory, borrower_type, loan_type, allowed_values, code_list) values",
    ]
    values = []
    for r in rows:
        allowed = [v for v in r["allowed_values"].split(" | ") if v]
        arr = "array[" + ", ".join(quote(v) for v in allowed) + "]::text[]" if allowed else "'{}'"
        values.append(
            "  ("
            + ", ".join(
                [
                    quote(r["field_id"]),
                    quote(r["template_id"]),
                    quote(r["field_name"]),
                    quote(r["data_type"]),
                    quote(column_name(r["field_id"], r["field_name"])),
                    "true" if r["mandatory"] == "Y" else "false",
                    quote(r["borrower_type"]),
                    quote(r["loan_type"]),
                    arr,
                    quote(r["code_list"]) if r["code_list"] else "null",
                ]
            )
            + ")"
        )
    lines.append(",\n".join(values) + ";")
    OUT.write_text("\n".join(lines) + "\n", encoding="utf-8")
    print(f"wrote {OUT.relative_to(ROOT)}: {len(rows)} fields")


if __name__ == "__main__":
    main()
