"""Development seed (supabase/seed.sql): synthetic tenants, users for every role, portfolios and
a few hundred accounts. Deterministic: identical output for the same seed.

Users log in with an email code (Mailpit locally). Emails use the reserved `.test` domain.
"""

from __future__ import annotations

import datetime as dt
import random
import uuid
from collections.abc import Iterable, Sequence
from dataclasses import dataclass
from decimal import Decimal

from faker import Faker

from collectoo_worker.synth.ids import siren, siret

NS = uuid.UUID("6f1c5a52-6f1e-4c39-9a3c-0c0ffee0c011")
SERVICER = "Collectoo"
CLIENTS = (
    ("martin", "Fournitures Martin SARL", "b2b_invoice", "commercial_b2b", "Factures 2026"),
    ("lilas", "Foncière des Lilas", "rent", "civil", "Loyers impayés"),
)
USERS = (
    ("admin@collectoo.test", None, "admin"),
    ("ops@collectoo.test", None, "ops_manager"),
    ("collecteur@collectoo.test", None, "collector"),
    ("admin@martin.test", "martin", "client_admin"),
    ("lecture@martin.test", "martin", "client_viewer"),
    ("admin@lilas.test", "lilas", "client_admin"),
)


@dataclass(frozen=True)
class ClientCtx:
    key: str
    servicer: str
    client: str
    portfolio: str
    claim_type: str
    regime: str


def uid(*parts: object) -> str:
    return str(uuid.uuid5(NS, "/".join(str(p) for p in parts)))


def q(value: object) -> str:
    if value is None:
        return "null"
    if isinstance(value, bool):
        return "true" if value else "false"
    if isinstance(value, int | Decimal):
        return str(value)
    return "'" + str(value).replace("'", "''") + "'"


def insert(table: str, cols: list[str], rows: Iterable[Sequence[object]]) -> list[str]:
    values = [f"  ({', '.join(q(v) for v in row)})" for row in rows]
    if not values:
        return []
    return [f"insert into {table} ({', '.join(cols)}) values", ",\n".join(values) + ";", ""]


def seed_sql(seed: int = 1, accounts_per_client: int = 125) -> str:
    rng = random.Random(seed)
    fake = Faker("fr_FR")
    fake.seed_instance(seed)
    out = [
        "-- GENERATED by `make seed` (collectoo_worker.synth.seed). Synthetic data only.",
        "-- Users log in with an email code: read it in Mailpit (http://127.0.0.1:54324).",
        "",
        "select set_config('app.actor', 'seed', false);",
        "",
    ]
    servicer = uid("org", "servicer")
    out += insert(
        "public.organization", ["id", "kind", "legal_name"], [[servicer, "servicer", SERVICER]]
    )
    out += insert(
        "public.organization",
        ["id", "kind", "servicer_organization_id", "legal_name", "siren"],
        [
            [uid("org", key), "creditor_client", servicer, name, siren(rng)]
            for key, name, *_ in CLIENTS
        ],
    )

    users = []
    identities = []
    for email, _, _ in USERS:
        user_id = uid("user", email)
        users.append(
            [
                "00000000-0000-0000-0000-000000000000", user_id, "authenticated", "authenticated",
                email, "2026-01-01 00:00:00+00", "", "", "", "", "{}", "{}",
                "2026-01-01 00:00:00+00", "2026-01-01 00:00:00+00",
            ]
        )  # fmt: skip
        identities.append(
            [
                user_id, user_id, f'{{"sub": "{user_id}", "email": "{email}"}}', "email",
                "2026-01-01 00:00:00+00", "2026-01-01 00:00:00+00",
            ]
        )  # fmt: skip
    out += insert(
        "auth.users",
        [
            "instance_id", "id", "aud", "role", "email", "email_confirmed_at", "confirmation_token",
            "recovery_token", "email_change_token_new", "email_change", "raw_app_meta_data",
            "raw_user_meta_data", "created_at", "updated_at",
        ],
        users,
    )  # fmt: skip
    out += insert(
        "auth.identities",
        [
            "provider_id",
            "user_id",
            "identity_data",
            "provider",
            "created_at",
            "updated_at",
        ],
        identities,
    )
    out += insert(
        "public.membership",
        ["user_id", "organization_id", "role"],
        [[uid("user", e), uid("org", c) if c else servicer, r] for e, c, r in USERS],
    )

    for key, _name, claim_type, regime, portfolio_name in CLIENTS:
        client = uid("org", key)
        mandate = uid("mandate", key)
        portfolio = uid("portfolio", key)
        out += insert(
            "public.mandate",
            [
                "id",
                "organization_id",
                "client_organization_id",
                "reference",
                "mandate_type",
                "signed_on",
            ],
            [
                [
                    mandate,
                    servicer,
                    client,
                    f"MAND-{key.upper()}-2026",
                    "mandate_amicable",
                    "2026-01-15",
                ]
            ],
        )
        out += insert(
            "public.mandate_terms",
            ["mandate_id", "valid_from", "commission_rate", "remittance_max_days", "plan_envelope"],
            [
                [
                    mandate,
                    "2026-01-15",
                    Decimal("0.1500"),
                    30,
                    '{"max_months": 12, "min_instalment_minor": 3000}',
                ]
            ],
        )
        out += insert(
            "public.portfolio",
            [
                "id",
                "organization_id",
                "client_organization_id",
                "name",
                "default_claim_type",
                "mandate_id",
            ],
            [[portfolio, servicer, client, portfolio_name, claim_type, mandate]],
        )
        ctx = ClientCtx(key, servicer, client, portfolio, claim_type, regime)
        out += _accounts(fake, rng, ctx, accounts_per_client)
    out += [
        "-- M2-06: each workable account gets its RF payment reference (random, drawn at load).",
        "select private.issue_payment_references(null);",
        "",
    ]
    return "\n".join(out)


def _accounts(fake: Faker, rng: random.Random, ctx: ClientCtx, n: int) -> list[str]:
    key, servicer, client, portfolio = ctx.key, ctx.servicer, ctx.client, ctx.portfolio
    claim_type, regime = ctx.claim_type, ctx.regime
    b2b = claim_type == "b2b_invoice"
    parties: list[list[object]] = []
    idents: list[list[object]] = []
    contacts: list[list[object]] = []
    accounts: list[list[object]] = []
    links: list[list[object]] = []
    items: list[list[object]] = []
    owners: list[list[object]] = []
    for i in range(1, n + 1):
        party = uid("party", key, i)
        account = uid("account", key, i)
        if b2b:
            sir = siren(rng)
            parties.append(
                [party, servicer, client, "legal_entity", fake.company(), None, None, f"C{i:05d}"]
            )
            idents += [[party, "siren", sir], [party, "siret", siret(rng, sir)]]
        else:
            first, last = fake.first_name(), fake.last_name()
            parties.append(
                [
                    party,
                    servicer,
                    client,
                    "natural_person",
                    f"{last.upper()} {first}",
                    first,
                    last,
                    f"L{i:05d}",
                ]
            )
        contacts.append(
            [party, "postal", f"{fake.street_address()}, {fake.postcode()} {fake.city()}", "seller"]
        )
        if rng.random() < 0.8:
            contacts.append([party, "email", fake.email(), "seller"])
        if rng.random() < 0.85:
            contacts.append([party, "phone", fake.phone_number(), "seller"])
        status = rng.choice(
            ["in_collection"] * 6 + ["arrangement", "awaiting_first_letter", "closed_paid"]
        )
        accounts.append(
            [
                account,
                portfolio,
                claim_type,
                f"{key.upper()}-{i:05d}",
                regime,
                status,
                servicer,
                client,
            ]
        )
        links.append([account, party, "borrower", "legal_entity" if b2b else "consumer"])
        owners.append([account, client, servicer, "mandate_amicable", "2026-01-15"])
        for j in range(1, rng.randint(1, 3) + 1):
            issue = dt.date(2026, 1, 1) + dt.timedelta(days=rng.randint(0, 250))
            if b2b:
                items.append(
                    [
                        account,
                        "invoice",
                        f"F2026-{i:05d}-{j}",
                        issue,
                        issue + dt.timedelta(days=30),
                        rng.randint(8_000, 900_000),
                    ]
                )
            else:
                items.append(
                    [
                        account,
                        "rent_period",
                        f"{issue:%Y-%m}",
                        issue.replace(day=1),
                        issue.replace(day=5),
                        rng.randint(45_000, 150_000),
                    ]
                )
    # Two rent periods drawn in the same month would share a ref: keep the first.
    unique_items: dict[tuple[object, object], list[object]] = {}
    for item in items:
        unique_items.setdefault((item[0], item[2]), item)
    items = list(unique_items.values())
    out: list[str] = []
    out += insert(
        "public.party",
        [
            "id",
            "organization_id",
            "client_organization_id",
            "kind",
            "display_name",
            "first_name",
            "last_name",
            "seller_ref",
        ],
        parties,
    )
    out += insert("public.party_identifier", ["party_id", "scheme", "value"], idents)
    out += insert("public.contact_point", ["party_id", "type", "value_raw", "source"], contacts)
    out += insert(
        "public.account",
        [
            "id",
            "portfolio_id",
            "claim_type_code",
            "external_ref",
            "legal_regime",
            "status",
            "organization_id",
            "client_organization_id",
        ],
        accounts,
    )
    out += insert("public.account_party", ["account_id", "party_id", "role", "capacity"], links)
    out += insert(
        "public.claim_item",
        ["account_id", "kind", "ref", "issue_date", "due_date", "original_minor"],
        items,
    )
    out += insert(
        "public.claim_ownership_period",
        [
            "account_id",
            "owner_organization_id",
            "servicer_organization_id",
            "mandate_type",
            "valid_from",
        ],
        owners,
    )
    return out
