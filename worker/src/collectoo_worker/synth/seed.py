def _billing(servicer: str, servicer_siren: str) -> list[str]:
    """M2c-2: the billing identities (servicer and clients) and each client's signed mandate (a
    synthetic document row: no file is stored for it)."""
    office = json.dumps(SERVICER_OFFICE, ensure_ascii=False)
    rows: list[list[object]] = [
        [servicer, "SAS", 1_000_000, "Paris", office, fr_vat_number(servicer_siren), True]
    ]
    docs: list[list[object]] = []
    for key, *_ in CLIENTS:
        client = uid("org", key)
        address = json.dumps(CLIENT_OFFICE[key], ensure_ascii=False)
        rows.append([client, None, None, None, address, None, True])
        doc = uid("document", "mandate", key)
        docs.append(
            [
                doc,
                servicer,
                client,
                "mandate_document",
                "documents",
                f"client/{servicer}/{client}/{doc}.pdf",
                hashlib.sha256(f"synthetic mandate {key}".encode()).hexdigest(),
                "application/pdf",
                f"MAND-{key.upper()}-2026.pdf",
            ]
        )
    out = insert(
        "public.billing_identity",
        [
            "organization_id",
            "legal_form",
            "share_capital_minor",
            "rcs_city",
            "registered_office",
            "vat_number",
            "is_professional",
        ],
        rows,
    )
    return out + insert(
        "public.document",
        [
            "id",
            "organization_id",
            "client_organization_id",
            "kind",
            "storage_bucket",
            "storage_path",
            "sha256",
            "mime_type",
            "file_name",
        ],
        docs,
    )


def _accounts(fake: Faker, rng: random.Random, ctx: ClientCtx, n: int) -> list[str]:
    key, servicer, client, portfolio = ctx.key, ctx.servicer, ctx.client, ctx.portfolio
    claim_type, regime = ctx.claim_type, ctx.regime
    b2b = claim_type == "b2b_invoice"
    parties: list[list[object]] = []
    idents: list[list[object]] = []
    contacts: list[list[object]] = []
    accounts: list[list[object]] = []
    links: list[list[object]] = []
    items: list[list[object]] = []
    owners: list[list[object]] = []
    for i in range(1, n + 1):
        party = uid("party", key, i)
        account = uid("account", key, i)
        if b2b:
            sir = siren(rng)
            parties.append(
                [party, servicer, client, "legal_entity", fake.company(), None, None, f"C{i:05d}"]
            )
            idents += [[party, "siren", sir], [party, "siret", siret(rng, sir)]]
        else:
            first, last = fake.first_name(), fake.last_name()
            parties.append(
                [
                    party,
                    servicer,
                    client,
                    "natural_person",
                    f"{last.upper()} {first}",
                    first,
                    last,
                    f"L{i:05d}",
                ]
            )
        contacts.append(
            [party, "postal", f"{fake.street_address()}, {fake.postcode()} {fake.city()}", "seller"]
        )
        if rng.random() < 0.8:
            contacts.append([party, "email", fake.email(), "seller"])
        if rng.random() < 0.85:
            contacts.append([party, "phone", fake.phone_number(), "seller"])
        status = rng.choice(
            ["in_collection"] * 6 + ["arrangement", "awaiting_first_letter", "closed_paid"]
        )
        accounts.append(
            [
                account,
                portfolio,
                claim_type,
                f"{key.upper()}-{i:05d}",
                regime,
                status,
                servicer,
                client,
            ]
        )
        links.append([account, party, "borrower", "legal_entity" if b2b else "consumer"])
        owners.append([account, client, servicer, "mandate_amicable", "2026-01-15"])
        for j in range(1, rng.randint(1, 3) + 1):
            issue = dt.date(2026, 1, 1) + dt.timedelta(days=rng.randint(0, 250))
            if b2b:
                items.append(
                    [
                        account,
                        "invoice",
                        f"F2026-{i:05d}-{j}",
                        issue,
                        issue + dt.timedelta(days=30),
                        rng.randint(8_000, 900_000),
                    ]
                )
            else:
                items.append(
                    [
                        account,
                        "rent_period",
                        f"{issue:%Y-%m}",
                        issue.replace(day=1),
                        issue.replace(day=5),
                        rng.randint(45_000, 150_000),
                    ]
                )
    # Two rent periods drawn in the same month would share a ref: keep the first.
    unique_items: dict[tuple[object, object], list[object]] = {}
    for item in items:
        unique_items.setdefault((item[0], item[2]), item)
    items = list(unique_items.values())
    out: list[str] = []
    out += insert(
        "public.party",
        [
            "id",
            "organization_id",
            "client_organization_id",
            "kind",
            "display_name",
            "first_name",
            "last_name",
            "seller_ref",
        ],
        parties,
    )
    out += insert("public.party_identifier", ["party_id", "scheme", "value"], idents)
    out += insert("public.contact_point", ["party_id", "type", "value_raw", "source"], contacts)
    out += insert(
        "public.account",
        [
            "id",
            "portfolio_id",
            "claim_type_code",
            "external_ref",
            "legal_regime",
            "status",
            "organization_id",
            "client_organization_id",
        ],
        accounts,
    )
    out += insert("public.account_party", ["account_id", "party_id", "role", "capacity"], links)
    out += insert(
        "public.claim_item",
        ["account_id", "kind", "ref", "issue_date", "due_date", "original_minor"],
        items,
    )
    out += insert(
        "public.claim_ownership_period",
        [
            "account_id",
            "owner_organization_id",
            "servicer_organization_id",
            "mandate_type",
            "valid_from",
        ],
        owners,
    )
    return out
