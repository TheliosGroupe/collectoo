-- request_refund (redefined from 20261110120000): + p_execution_mode (last, defaulted: the old signature is dropped so
-- that one function answers). Same settings; grants restated below.
drop function public.request_refund(text, uuid, text, text, text, text, text, text, text);
create function public.request_refund(p_idempotency_key text, p_payment_id uuid, p_amount_minor text,
                                      p_payee_iban text, p_payee_name text, p_reason_code text,
                                      p_expected_review_reason text, p_expected_left_minor text,
                                      p_reason text, p_execution_mode text default null)
returns jsonb
language plpgsql
security definer
set search_path = ''
set lock_timeout = '2s'
as $$
declare
  p public.payment;
  v_reason text := btrim(coalesce(p_reason, ''));
  v_request jsonb;
  v_result jsonb;
  pos record;
  v_amount bigint;
  v_payer text;
  v_iban text;
  v_name text;
  v_e2e text;
  v_id uuid;
  v_fits boolean;
  v_filable boolean;
  v_sepa boolean;
  v_epc boolean;
  v_mode text;
  v_transfer uuid;
begin
  select * into p from public.payment where id = p_payment_id;
  if not found or not private.has_role(p.organization_id, array['admin', 'ops_manager']) then
    raise exception 'not allowed' using errcode = 'insufficient_privilege';
  end if;
  v_request := jsonb_build_object('payment_id', p_payment_id, 'amount_minor', p_amount_minor, 'payee_iban', p_payee_iban,
                                  'payee_name', p_payee_name, 'reason_code', p_reason_code,
                                  'expected_review_reason', p_expected_review_reason,
                                  'expected_left_minor', p_expected_left_minor, 'reason', v_reason,
                                  'execution_mode', p_execution_mode);
  v_result := private.command_replay('request_refund', p_idempotency_key, v_request);
  if v_result is not null then
    return v_result;
  end if;
  if v_reason = '' or length(v_reason) > 2000 then
    raise exception 'a reason is required' using errcode = 'check_violation';
  end if;
  if coalesce(p_amount_minor, '') !~ '^[0-9]{1,16}$' or p_amount_minor::bigint <= 0 then
    raise exception 'refund: invalid amount' using errcode = 'check_violation';
  end if;
  v_amount := p_amount_minor::bigint;
  -- file first, then the payment (ADR-0013 lock order)
  if p.account_id is not null then
    perform 1 from public.account a where a.id = p.account_id for key share;
  end if;
  select * into p from public.payment where id = p_payment_id for update;
  select * into pos from private.payment_positions(array[p.id]);
  if p.review_reason is distinct from p_expected_review_reason or p_expected_left_minor is distinct from pos.unallocated_minor::text then
    raise exception 'the payment changed: reload the page' using errcode = 'check_violation';
  end if;
  -- What is left and not waiting for allocation: unmatched, or held for a reason ops decide.
  if not (p.status = 'unmatched' or (p.status in ('matched', 'partially_allocated') and p.review_reason is not null)) then
    raise exception 'refund: this payment cannot be refunded from here' using errcode = 'check_violation';
  end if;
  if v_amount > pos.unallocated_minor then
    raise exception 'refund: more than what is left of the payment' using errcode = 'check_violation';
  end if;
  v_fits := case p_reason_code
      when 'overpayment' then p.review_reason in ('overpayment', 'nothing_due')
      when 'currency_mismatch' then p.review_reason = 'currency_mismatch'
      when 'no_mandate' then p.review_reason = 'no_mandate'
      when 'unidentified' then p.status = 'unmatched' and p.review_reason in ('no_match', 'ambiguous')
      when 'held_file' then p.review_reason = 'hold_blocks_allocation'
      when 'account_closed' then p.review_reason = 'account_closed'
      when 'partial_return' then p.review_reason = 'partial_return'
      when 'other' then true
      else false end;
  if not coalesce(v_fits, false) then
    raise exception 'refund: the reason does not match the payment''s state' using errcode = 'check_violation';
  end if;
  v_payer := nullif(private.rf_normalise(coalesce(p.payer_iban, '')), '');
  v_iban := coalesce(nullif(private.rf_normalise(coalesce(p_payee_iban, '')), ''), v_payer);
  if v_iban is null then
    raise exception 'refund: the payee''s IBAN is required (the bank gave none)' using errcode = 'check_violation';
  end if;
  if not private.iban_valid(v_iban) then
    raise exception 'refund: invalid IBAN' using errcode = 'check_violation';
  end if;
  v_name := coalesce(nullif(btrim(coalesce(p_payee_name, '')), ''), nullif(btrim(coalesce(p.payer_name, '')), ''));
  if v_name is null or length(v_name) > 140 then
    raise exception 'refund: the payee''s name is required' using errcode = 'check_violation';
  end if;
  -- M2c-6a (founder #15, M2b-6 #13): in the next transfer file of the payment's account when it is the servicer's active
  -- dedicated account in EUR (the default then); by hand in the bank otherwise, or when ops say so ('manual': e.g.
  -- already executed). A refund in a file is never executed by hand: its RFD debit books it (the M2b link), and its
  -- transfer follows it (private.refund_transfer_follow).
  -- Review T3: by hand too when no SCT file can carry it — an IBAN outside the SEPA schemes, a name with no EPC
  -- character (the default then; asked in a file: refused).
  v_filable := p.currency = 'EUR' and exists (select 1 from public.bank_account b where b.id = p.bank_account_id
                                                and b.purpose = 'client_funds' and b.status = 'active');
  v_sepa := private.iban_in_sepa(v_iban);
  v_epc := not private.epc_name_empty(btrim(left(v_name, 70)));
  v_mode := coalesce(p_execution_mode, case when v_filable and v_sepa and v_epc then 'file' else 'manual' end);
  if v_mode not in ('manual', 'file') then
    raise exception 'refund: unknown execution mode' using errcode = 'check_violation';
  end if;
  if v_mode = 'file' and not v_filable then
    raise exception 'refund: this account pays no transfer file (an active dedicated account in EUR)'
      using errcode = 'check_violation';
  end if;
  if v_mode = 'file' and not v_sepa then
    raise exception 'refund refused: iban_not_sepa' using errcode = 'check_violation';
  end if;
  if v_mode = 'file' and not v_epc then
    raise exception 'refund refused: payee_name_not_epc' using errcode = 'check_violation';
  end if;
  v_e2e := 'RFD' || upper(substr(md5(gen_random_uuid()::text), 1, 12));
  if v_mode = 'file' then
    -- the payment row is held: then the allocation and remit locks, as every writer of a transfer (ADR-0014)
    perform private.remittance_command_locks(p.organization_id, true);
    insert into public.bank_transfer (organization_id, kind, debtor_bank_account_id, currency, amount_minor, payee_name,
                                      payee_iban, end_to_end_id, remittance_info, requested_execution_date, reason,
                                      ordered_by)
    values (p.organization_id, 'refund', p.bank_account_id, p.currency, v_amount, btrim(left(v_name, 70)), v_iban, v_e2e,
            'REMBOURSEMENT ' || v_e2e, private.transfer_earliest_execution_date(p.bank_account_id), v_reason, auth.uid())
    returning id into v_transfer;
  end if;
  insert into public.refund_request (organization_id, payment_id, bank_account_id, currency, amount_minor, payee_iban,
                                     payee_name, payee_is_payer, end_to_end_id, reason_code, reason, prior_status,
                                     prior_review_reason, requested_by, execution_mode, transfer_id)
  values (p.organization_id, p.id, p.bank_account_id, p.currency, v_amount, v_iban, v_name,
          v_iban is not distinct from v_payer, v_e2e, p_reason_code, v_reason, p.status, p.review_reason, auth.uid(),
          v_mode, v_transfer)
  returning id into v_id;
  update public.payment set status = 'refund_pending', review_reason = null, allocation_instruction = null where id = p.id;
  -- the debit may be on a statement already (ops executed the transfer before recording it)
  perform pgmq.send('payments', jsonb_build_object('type', 'process_debits', 'organization_id', p.organization_id));
  v_result := jsonb_build_object('refund_request_id', v_id, 'end_to_end_id', v_e2e, 'amount_minor', v_amount::text,
                                 'payee_iban_end', right(v_iban, 4), 'execution_mode', v_mode,
                                 'transfer_id', v_transfer);
  perform private.command_record('request_refund', p_idempotency_key, v_request, v_result);
  return v_result;
end;
$$;


-- The refund's transfer follows it: executed by its debit (the M2b link) → booked (a file not downloaded yet that holds
-- it is superseded first: it must never be uploaded with a refund already paid); cancelled → cancelled (refused while
-- a downloaded file holds it: its transfer is cancelled first, on the statements' evidence and by four eyes —
-- public.request_transfer_cancellation, or the file's; review T1, pain001#1); bounced → returned. Under the allocation
-- and remit locks (the refund and payment rows are held by the caller). Review round 3 (E2, N2): a refund is not
-- cancelled once its transfer, or one it re-issues, has left the account (`already_debited`: it would be refunded twice).
-- Review round 4 (G2, H16): nor executed by a debit carrying another end-to-end id than its transfer's own (a transfer
-- this one re-issues: its cancelled file executed late) while its transfer sits in a downloaded or sent file — that file,
-- uploaded, would refund it again; booked, the transfer would leave it un-cancellable (`reissue_in_downloaded_file`:
-- cancel that file on the statements' evidence first, then link). M2c-6b's booking of a payout by an old RMT id follows
-- the same rule (OQ-80 (n)). Review round 5 (fail-closed): with cancellation after download off, nothing is re-issued
-- and `cancelled` stays refused while a downloaded file holds the transfer; the hints say what to do now. Review round 6
-- (round 4's G2 rule, the prerequisite of switching it on, met now; round 5's verifier, p_link): while the transfer is
-- in a downloaded or sent file, `executed` is accepted only by a debit carrying that transfer's own end-to-end id, or by
-- a batch line (no end-to-end id) whose PmtInfId is that transfer's PmtInf in that file (its transfer_file_item) —
-- anything else, a predecessor file's batch line or another PmtInf's included, `reissue_in_downloaded_file`. Review
-- round 7 (the founder's decision on round 6's N1, option (b)): also by a line carrying neither an end-to-end id nor a
-- PmtInfId while that transfer re-issues none (`replaces_transfer_id` null: always so while cancellation after download
-- is off) — M2b's behaviour for a CSV feed without the reference column, which never carries a PmtInfId; such a line
-- is refused for a re-issue (it may be the old file's execution). The hint names the file and says what the line
-- carries, and « refunded a second time » only where that is so (a re-issue, the switch on).
create or replace function private.refund_transfer_follow()
returns trigger
language plpgsql
security definer
set search_path = ''
as $$
declare
  t public.bank_transfer;
  f public.transfer_file;
  x public.bank_transaction;
begin
  if new.transfer_id is null or new.status = old.status then
    return null;
  end if;
  perform private.remittance_command_locks(new.organization_id, true);
  select * into t from public.bank_transfer where id = new.transfer_id for update;
  if new.status in ('executed', 'cancelled') and t.status = 'in_file' then
    select * into f from public.transfer_file where id = t.transfer_file_id for update;
    if f.status in ('pending', 'generated') then
      perform private.transfer_file_release(f.id, 'superseded',
        case new.status when 'executed' then 'Remboursement ' || new.end_to_end_id || ' exécuté hors du fichier'
                        else 'Remboursement ' || new.end_to_end_id || ' annulé' end, null, null);
      select * into t from public.bank_transfer where id = t.id;
    -- review round 6 (round 4's G2 rule, now): executed only by a debit carrying this transfer's own end-to-end id, or
    -- by a batch line (no end-to-end id) of its own PmtInf in this file — never another id, another PmtInf (of this file,
    -- or a predecessor's: the re-issue would be booked here, its bytes still to be uploaded); review round 7 (N1 (b)):
    -- or by a line naming neither, while this transfer re-issues none (as in M2b: a CSV feed without the reference)
    elsif new.status = 'executed' and not exists (
            select 1 from public.bank_transaction b where b.id = new.bank_transaction_id
              and (b.end_to_end_id = t.end_to_end_id
                   or (b.end_to_end_id is null and b.payment_info_id = (
                         select i.pmt_inf_id from public.transfer_file_item i
                         where i.file_id = f.id and i.transfer_id = t.id))
                   or (b.end_to_end_id is null and b.payment_info_id is null and t.replaces_transfer_id is null))) then
      select * into x from public.bank_transaction where id = new.bank_transaction_id;
      raise exception 'refund refused: reissue_in_downloaded_file' using errcode = 'check_violation',
        detail = jsonb_build_object('file', f.number, 'transfer_id', t.id)::text,
        hint = 'Ce débit '
               || case when x.end_to_end_id is not null then 'porte la référence d''un autre virement'
                       when x.payment_info_id is not null then 'porte la référence d''un autre lot'
                       else 'ne porte aucune référence, et le virement de ce remboursement en remplace un autre' end
               || ' : il ne peut pas exécuter ce remboursement, dont le virement est dans le fichier ' || f.number
               || ', déjà téléchargé. '
               || case when private.switch_on('downloaded_file_cancellation') and t.replaces_transfer_id is not null
                       then 'S''il exécute, en retard, le virement que celui-ci remplace, faites d''abord annuler ce fichier, relevé à l''appui, puis rattachez ce débit : rattaché avant, le remboursement serait payé une seconde fois si la banque exécute ce fichier. Sinon, ne le rattachez pas à ce remboursement.'
                       else 'Ne le rattachez pas à ce remboursement ; gardez le fichier tel quel, vérifiez le relevé et voyez avec la banque.' end;
    elsif new.status = 'cancelled' then
      raise exception 'refund refused: in_downloaded_file' using errcode = 'check_violation',
        detail = jsonb_build_object('file', f.number, 'transfer_id', t.id)::text,
        hint = case when private.switch_on('downloaded_file_cancellation')
                    then 'Le fichier a été téléchargé : faites d''abord annuler son virement, relevé à l''appui.'
                    else 'Le virement de ce remboursement est dans un fichier déjà téléchargé : il reste en cours jusqu''à ce que son débit, ou son rejet, soit lu sur le relevé (l''annulation après téléchargement n''est pas encore disponible). Gardez le fichier tel quel, vérifiez le relevé et voyez avec la banque.' end;
    end if;
  end if;
  if new.status = 'executed' then
    update public.bank_transfer set status = 'booked', entry_id = new.cash_out_entry_id
    where id = t.id and status in ('ordered', 'in_file');
  elsif new.status = 'cancelled' then
    if private.transfer_debited_before(t.id) then
      raise exception 'refund refused: already_debited' using errcode = 'check_violation',
        detail = jsonb_build_object('transfer_id', t.id, 'end_to_end_id', t.end_to_end_id)::text,
        hint = 'Un relevé montre déjà le débit de ce remboursement (sous sa référence, celle du virement qu''il remplace, ou dans une ligne groupée de son lot) : ne l''annulez pas ; le débit sera rattaché.';
    end if;
    update public.bank_transfer set status = 'cancelled', cancelled_at = clock_timestamp(), cancelled_by = auth.uid(),
      cancel_reason = left('Remboursement annulé : ' || coalesce(new.cancel_reason, ''), 2000)
    where id = t.id and status = 'ordered';
  elsif new.status = 'bounced' then
    update public.bank_transfer set status = 'returned', return_entry_id = new.bounce_entry_id
    where id = t.id and status = 'booked';
  end if;
  return null;
end;
$$;
create trigger refund_request_transfer after update of status on public.refund_request
  for each row execute function private.refund_transfer_follow();
alter table public.refund_request enable always trigger refund_request_transfer;

