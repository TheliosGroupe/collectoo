-- What the writer needs, frozen at generation (null: superseded meanwhile, or another job's). The file row is held
-- FOR UPDATE until the job commits. Amounts as text.
create or replace function private.transfer_file_begin(p_file_id uuid, p_token uuid)
returns jsonb
language plpgsql
security definer
set search_path = ''
as $$
declare
  f public.transfer_file;
begin
  select * into f from public.transfer_file where id = p_file_id for update;
  if not found or f.status <> 'pending' or f.job_token <> p_token then
    return null;
  end if;
  return jsonb_build_object(
    'file_id', f.id, 'organization_id', f.organization_id, 'number', f.number, 'msg_id', f.msg_id,
    'version', f.pain_version, 'created_at', f.created_at_iso, 'initiating_party', f.initiating_party,
    'nb_of_txs', f.nb_of_txs, 'ctrl_sum_minor', f.ctrl_sum_minor::text,
    'storage_path', f.organization_id || '/' || f.id || '/' || f.number || '.xml',
    'payment_infos', (
      select jsonb_agg(jsonb_build_object(
               'pmt_inf_id', p.pmt_inf_id, 'execution_date', p.execution_date, 'debtor_name', f.debtor_name,
               'debtor_iban', f.debtor_iban, 'debtor_bic', f.debtor_bic, 'transactions', p.txs)
             order by p.first_seq)
      from (select i.pmt_inf_id, min(i.execution_date) as execution_date, min(i.seq) as first_seq,
                   jsonb_agg(jsonb_build_object(
                     'instr_id', case when t.kind = 'payout' then coalesce(r.number, t.end_to_end_id)
                                      else t.end_to_end_id end,
                     'end_to_end_id', t.end_to_end_id, 'amount_minor', t.amount_minor::text, 'currency', t.currency,
                     'creditor_name', t.payee_name, 'creditor_iban', t.payee_iban, 'creditor_bic', t.payee_bic,
                     'remittance_info', coalesce(t.remittance_info, ''))
                     order by i.seq) as txs
            from public.transfer_file_item i
            join public.bank_transfer t on t.id = i.transfer_id
            left join public.remittance_run r on r.id = t.run_id
            where i.file_id = f.id
            group by i.pmt_inf_id) p));
end;
$$;

-- The job wrote, checked and uploaded the bytes: their SHA-256, size, path and whether the XSD validated them; the
-- writer's NbOfTxs and CtrlSum must be the file's.
create or replace function private.transfer_file_record(p_file_id uuid, p_token uuid, p_sha256 text, p_size bigint,
                                                        p_storage_path text, p_xsd_validated boolean,
                                                        p_renderer_version text, p_nb_of_txs integer,
                                                        p_ctrl_sum_minor bigint)
returns jsonb
language plpgsql
security definer
set search_path = ''
as $$
declare
  f public.transfer_file;
begin
  select * into f from public.transfer_file where id = p_file_id for update;
  if not found or f.status <> 'pending' or f.job_token <> p_token then
    return jsonb_build_object('status', 'skipped');
  end if;
  if p_nb_of_txs <> f.nb_of_txs or p_ctrl_sum_minor <> f.ctrl_sum_minor
     or p_storage_path <> f.organization_id || '/' || f.id || '/' || f.number || '.xml' then
    raise exception 'transfer file %: the written file differs from what was generated', f.number using errcode = '23514';
  end if;
  update public.transfer_file set status = 'generated', file_sha256 = p_sha256, size_bytes = p_size,
    storage_path = p_storage_path, xsd_validated = p_xsd_validated, renderer_version = p_renderer_version,
    generated_at = clock_timestamp(), version = version + 1
  where id = f.id;
  return jsonb_build_object('status', 'generated', 'number', f.number);
end;
$$;

