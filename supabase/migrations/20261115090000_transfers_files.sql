-- M2c-6a Transfers and files (design docs/design/m2c-remittances.md §11 « Transfers and pain.001 », §6.1 bank_transfer /
-- transfer_file, §9.7 cancellation after download, §9.8 state machines, §9.9 idempotency, §15 alerts, §16 commands,
-- §17.3 « Virements »; founder #9, #14, #15; ADR-0014 M2c-6a addendum). The first half of M2c-6: the booking of the
-- debits from the statement (§12), the sweep's and the top-ups' bookings, returned payouts and the statement's
-- « Suivi » are M2c-6b. No ledger entry is posted here: client money leaves 5120 only at the bank's debit (§0, §5.2
-- `remittance`, `client_settlement`, `servicer_sweep` are dated at the debit), and generating, downloading or sending a
-- file is no bank fact.
--
--   * transfer files (public.transfer_file, its items public.transfer_file_item, its downloads
--     public.transfer_file_download): one live file per paying (client_funds) account, generated by
--     public.generate_transfer_file under the allocation then remit locks, holding every ordered transfer of the
--     account that passes the checks — client payouts, refunds asked with execution_mode 'file' (M2b-6 #13) and the
--     sweep of the servicer's settled share to its own account, in its own PmtInf, S = max(0, −Σ4679 − Σ sweeps
--     ordered or in a file) computed under the remit lock (a sweep is never re-issued: a superseded file's sweep is
--     cancelled and recomputed). The worker job `transfer_file` (remittances queue) writes the pain.001 bytes
--     (`.09` by default, `.03` per bank_account.pain_version), checks them, uploads them to the private bucket
--     `transfer-files` and records their SHA-256;
--   * the checks at generation: cash (the last imported closing balance − the debits imported after it − the
--     transfers in flight not seen on a statement − the manual refunds pending ≥ CtrlSum; short: the sweep is left
--     out first, then the file is refused), per client (N + D ≤ −4670[c] − c's other runs in flight, else
--     `payout_not_covered`), the payee (the run's payout blockers today, the payout account unchanged since approval),
--     ReqdExctnDt (≥ the account's next execution day: today only before its cut-off; after the run's earliest latest
--     execution date only with a late reason); a transfer that fails is held out with its reason;
--   * download (public.transfer_file_download): the web route checks the stored bytes against the SHA-256 before it
--     serves them; every download is recorded; a second one needs the warning acknowledged (« Déjà téléchargé par … —
--     ne le déposez pas deux fois »); the file's runs become `sent`; « Marquer comme transmis »
--     (public.mark_transfer_file_sent); public.cancel_transfer_file before download (superseded); after download
--     the file, or one transfer of it, by request and confirmation on the statements' evidence (review T1 below);
--   * public.cancel_remittance_run redefined (same signature): before download its file is superseded; a payout in a
--     downloaded file is cancelled first (review T1), then its run (§9.7);
--   * refunds in the file: public.request_refund redefined (execution_mode 'file' by default when the payment's
--     account is the servicer's paying account in EUR; 'manual' as in M2b-6), the refund's transfer kept in step with
--     it (booked by the M2b-6 RFD link only, cancelled with it);
--   * verification of payee (Reg. 260/2012 art. 5 quater; founder #15, OQ-50): public.payee_name_check, recorded by ops
--     on the bank's no-match or close-match, blocks the client's payout accounts carrying that IBAN
--     (`payee_name_mismatch`) until another person — none of who recorded it, or proposed or confirmed that IBAN —
--     clears it, or no current payout account of the client carries that IBAN any more (a replacement with another
--     IBAN; the same IBAN confirmed again stays blocked, and a check closed so reopens if it does: review round 2, S1);
--   * alerts (§15): transfer_not_filed, file_not_downloaded, file_not_marked_sent, transfer_not_debited,
--     transfer_file_failed, transfer_file_pending, payee_name_mismatch, payee_name_not_epc, iban_not_sepa (nightly,
--     and from the hourly schedule once a cut-off passed or a file stays pending).
--
-- Redefined with their settings and grants restated: private.bank_transfer_guard (in_file → ordered when its file is
-- superseded; the file's id; a sweep goes to the servicer's own account), private.remittance_run_guard (sent →
-- approved when its file is cancelled), private.remittance_payout_blockers (+ payee_name_mismatch),
-- public.request_refund (+ p_execution_mode: dropped and created), public.cancel_remittance_run (same signature),
-- private.queue_remittance_schedule (+ the transfer checks due). private.run_remittance_checks is renamed
-- private.run_remittance_runs_checks (its body unchanged) and a new private.run_remittance_checks calls it, then the
-- transfer checks.
-- Lock order (ADR-0014): run rows → allocation lock → remit lock → file rows → transfer rows; every writer of a
-- transfer's or a file's status holds the remit lock.
--
-- M2c-6a review (risk R4, design §9.7, §11, §12, §15):
--   * T1 a downloaded or sent file is cancelled (its transfers re-queued), and one transfer of it refused by the bank
--     is cancelled, only on evidence and by four eyes: public.request_transfer_file_cancellation /
--     confirm_transfer_file_cancellation and public.request_transfer_cancellation / confirm_transfer_cancellation
--     (public.transfer_cancellation_request): the imported statements of the paying account cover every business day
--     from its execution date to the next business day and show no debit of it (by end-to-end id, or a batch debit by
--     PmtInfId — design §12's rule), or its return; a different money-staff member confirms. A run whose payout is
--     in a downloaded file is cancelled only once that transfer is (`payout_in_downloaded_file`);
--   * T2 the first download re-runs the generation checks under the same locks (the date against the account's
--     next execution day, every transfer's hold reason, the cash check): a stale file is superseded, not served
--     (`file_stale`, `file_blocked`), and the next generation takes its transfers again;
--   * T3 a payee name with no EPC character (`payee_name_not_epc`) or an IBAN outside the SEPA schemes' countries
--     (`iban_not_sepa`, private.sepa_scheme_country: EPC409-09) is held out of the file, not failing it;
--   * T4 the bucket's one policy (private.can_read_transfer_file_object) opens a file's bytes only to the member who
--     recorded its download through the command in the last 60 seconds, while the file is downloaded or sent; T5 a
--     payee check is cleared by none of who recorded it, proposed or confirmed the IBAN; T6 `file_not_marked_sent` at
--     the cut-off and `transfer_file_pending` through the hourly schedule; T7 file numbers never truncate.
--
-- M2c-6a review, round 2 (the skeptics' scenarios A–D and s5; design §9.7, §11, §12; COMPLIANCE OQ-80):
--   * D1 a day counts as covered by an imported statement only once it is over: the evidence window ends before
--     today (Paris), and each of its business days is in a statement uploaded after that day — a CSV's last booking
--     day never (its export time is unknown); at request and at confirmation, for a file and for one transfer;
--   * D2 one transfer of a downloaded file is cancelled only when the bank executed something of the file (a debit of
--     one of its end-to-end ids or PmtInfIds, or a return): otherwise `file_not_executed`, the file's own cancellation
--     being the exit; a downloaded file holding a cancelled transfer and nothing of it executed is never marked as sent
--     (`holds_cancelled_transfer`) nor alerted as not marked;
--   * D3 a batch debit with no end-to-end id is evidence for one transfer only when no other open transfer of its
--     PmtInf, alone or combined, makes up its amount (`batch_ambiguous`; private.amounts_make_up);
--   * D4 a payout or refund whose end-to-end id a statement already shows debited is held (`already_debited`) at
--     generation and at download, and alerted (`transfer_already_debited`); no sweep is issued while a cancelled sweep
--     of a downloaded file has its debit seen and no return (`cancelled_sweep_debited`);
--   * S1 an open payee check follows the client's IBAN, not the account row: it blocks every current payout account of
--     the client with that IBAN, closes only once none carries it, and none of who recorded it, or proposed or
--     confirmed that IBAN for the client, clears it.
--
-- M2c-6a review, round 3 (the skeptics' N1–N6 of round 2; design §9.7, §11, §12; COMPLIANCE OQ-80 (f), (i)–(m)):
--   * E1 a downloaded file cancelled whole never hands its end-to-end ids on: each payout and refund in it is cancelled
--     and re-issued as a new transfer under a fresh id (bank_transfer.replaces_transfer_id names the old one; the run's
--     and the refund's transfer, and the refund's RFD id, move to it; the sweep is cancelled and recomputed as before),
--     so an old id belongs only to a cancelled transfer (§9.7: a later debit of it is never booked automatically,
--     M2c-6b's unplanned payout); private.transfer_file_executed and the evidence read only the transfers a file holds;
--   * E2 private.transfer_debited_before: a transfer, or one in its replaces chain, shows a debit of its own end-to-end
--     id (not its own execution out of the downloaded file it is in), or a batch line of a PmtInf that held it in a
--     downloaded file cancelled since can contain it (private.batch_debit_may_hold: its amount alone or with others of
--     the PmtInf); a returned one left nothing. It holds the transfer (`already_debited`), alerts it
--     (`transfer_already_debited`, a re-issue already in a downloaded file too), stops the sweep
--     (private.debited_cancelled_sweeps) and refuses cancelling its run (`transfer_already_debited`) or refund
--     (`already_debited`);
--   * E3 a transfer of a batch-booked PmtInf whose return is seen was paid in the batch: it stays in the batch's sum
--     once cancelled (private.pmt_inf_batch_seen, the evidence) and never stands in for another;
--   * E4 a camt.053 covers a day only once the bank produced it after that day: its Stmt/CreDtTm (GrpHdr/CreDtTm as
--     fallback) is kept on bank_statement.bank_created_at at the import, and the parser ends a period whose ToDtTm is
--     the next midnight the day before; a CSV keeps round 2's rule. private.refund_request_guard (20261110120000) is
--     redefined for E1's re-issue, its settings unchanged.
--
-- M2c-6a review, round 4 (the skeptics' NEW-G1–G3 and residual (b) of round 3; COMPLIANCE OQ-80 (f), (n), (o)):
--   * G1 a payout, refund or sweep cancelled alone out of a downloaded file still live (the bank refused it) has left
--     the account when a batch line of its PmtInf booked after its cancellation's window can contain it
--     (private.transfer_debited_before, private.batch_debit_may_hold's p_after): its run or refund is not cancelled, no
--     sweep is issued meanwhile, and it is alerted (`transfer_already_debited`, while its run or refund is live);
--   * G2 a refund is not executed by a debit of another end-to-end id than its transfer's (a transfer it re-issues)
--     while that transfer sits in a downloaded or sent file (`reissue_in_downloaded_file`: cancel that file first);
--   * G3 a camt.053 covers a day only within one of its sections' whole days (`covers_from` … `covers_to`, the parser
--     reading FrToDt in Paris time; validated at the import) and never across a break in the sections' balances;
--   * G4 a downloaded or sent file holding a payout or refund that left the account already is not served again
--     (`holds_debited_transfer`).
--
-- M2c-6a review, round 5: fail-closed (founder-level decision; ADR-0014 « M2c-6a review fixes », round 5; design §9.7;
-- COMPLIANCE SEPA-01, OQ-80, OQ-81). Four rounds kept finding ways a transfer cancelled out of a file the bank already
-- has could be paid late and then paid again (round 4 still: a refund's predecessor-file batch line linked while its
-- re-issue sits in a downloaded file; a second sweep after a cancelled one debited late; a refused transfer executed
-- late as a batch line after its run or refund was cancelled), and the statements alone can never prove a transfer will
-- not be executed later. So once a file is downloaded nothing in it is cancelled, re-issued or re-queued until M2c-6b
-- books its debits from the statements: rounds 1–4's cancellation machinery stays, tested (pgTAP 028–032 switch it on
-- in their own transaction), behind private.feature_switch 'downloaded_file_cancellation', seeded off here;
-- private.switch_on reads it (false for an unknown key); no public function writes it — M2c-6b's migration switches it
-- on once the three paths above are closed. A payout the bank refuses, or a file never uploaded, stays « en cours »
-- until then: slower money, never double money (OQ-81). Every path that could move a payout, refund or sweep of a
-- downloaded or sent file out of in_file, change such a file's status or put its item back in a queue, and why it is
-- closed while the switch is off (pgTAP 033):
--   * public.cancel_transfer_file: a downloaded or sent file is refused `bank_booking_required` (in place of
--     `cancellation_request_required`); a pending or generated one is superseded as before (nothing was handed out);
--   * public.request_transfer_file_cancellation, confirm_transfer_file_cancellation, request_transfer_cancellation,
--     confirm_transfer_cancellation: refused `bank_booking_required` right after the permission check and the
--     idempotency replay, before any lock or state change — a request opened while the switch was on is never
--     confirmed once it is off;
--   * private.transfer_file_release (the only re-issue and re-queue): its callers other than the gated confirmation
--     release only a pending or generated file — generate_transfer_file (the account's pending and generated files),
--     private.transfer_file_failed (pending), transfer_file_download (its generated branch: stale or blocked),
--     cancel_transfer_file and cancel_remittance_run (their file pending or generated), private.refund_transfer_follow
--     (pending or generated) —, and the two guards below refuse it for a downloaded file whoever calls it;
--   * private.transfer_file_guard: downloaded or sent → superseded or rejected refused while the switch is off, whoever
--     writes it; private.bank_transfer_guard: in_file → ordered or cancelled refused for a transfer of a file downloaded
--     at least once (in_file → booked stays: a refund's own debit, M2b's link);
--   * public.cancel_remittance_run: its payout in_file in a downloaded or sent file is refused
--     `payout_in_downloaded_file` (that transfer can no longer be cancelled first); a payout ordered, or cancelled
--     before download, as before. private.remittance_run_guard lets a sent run go back to approved only once its
--     transfer is ordered again — unreachable for a downloaded file's payout — and (round 6) refuses its cancellation
--     while that payout is in_file in a downloaded file, whoever writes it;
--   * every refund_request status write — public.cancel_refund, a payment's full return cancelling its pending refund
--     and the M2b links executing or bouncing it (private.debit_post_rows, from link_debit and the process_debits
--     job) — goes through
--     private.refund_transfer_follow (trigger, enabled always): `cancelled` while its transfer is in a downloaded or
--     sent file is refused (`in_downloaded_file`); `executed` books the transfer (its debit read from the statement, not
--     a cancellation) — since round 6 only by its own end-to-end id or a batch line of its own PmtInf in that file, or
--     (round 7) a line naming neither while the transfer re-issues none, anything else `reissue_in_downloaded_file`;
--     `bounced` only from booked;
--   * public.record_payee_name_mismatch, clear_payee_name_mismatch: write payee_name_check only; they hold or free
--     transfers not filed yet (private.transfer_hold_reason at generation and at a generated file's first download), a
--     downloaded file's transfers stay in_file;
--   * public.generate_transfer_file files only ordered transfers (a downloaded file's are in_file; its sweep counts in
--     the sweeps in a file); transfer_file_download changes no downloaded or sent file's status (served, or refused
--     `holds_cancelled_transfer` / `holds_debited_transfer` / `file_executed`); mark_transfer_file_sent moves
--     downloaded → sent only;
--   * private.run_transfer_checks, transfer_checks_due, queue_remittance_schedule and the evidence helpers only read
--     (and alert); the worker's jobs write transfers only through these functions (private.transfer_file_begin, _record,
--     _failed: a pending file; the approval: ordered payouts; the debit links: the refund trigger above; the bank-line
--     bookings: an ordered top-up only), and public.cancel_top_up cancels only an ordered top-up (never in a file).
-- The pages read the switch (`cancellation_after_download` in transfer_file_detail and transfer_overview; no
-- cancellation card while it is off) and the refusal hints that sent ops to a cancellation say what to do now.
--
-- M2c-6a review, round 6 (round 5's verifiers; ADR-0014 « M2c-6a review fixes », round 6; COMPLIANCE OQ-80 (n), OQ-81
-- (c)):
--   * private.remittance_run_guard: an approved or sent run is not cancelled while its payout is in_file in a file
--     downloaded at least once and the switch is off, whoever writes it (postgres, service_role) — defence in depth
--     behind cancel_remittance_run's `payout_in_downloaded_file`;
--   * public.transfer_file_download: a downloaded or sent file the bank executed, in full or in part
--     (private.transfer_file_executed, or one of its payouts, refunds or sweeps with its own debit seen, or — round 7,
--     N5 — booked or returned already, e.g. a refund booked by a reference-less CSV line), is not served again
--     (`file_executed`), whatever the switch and the acknowledgement — uploaded again it would pay it all twice;
--   * private.refund_transfer_follow: round 4's G2 rule now — while the refund's transfer is in a downloaded or sent
--     file, `executed` only by that transfer's own end-to-end id or a batch line (no end-to-end id) whose PmtInfId is its
--     transfer_file_item.pmt_inf_id in that file; anything else `reissue_in_downloaded_file` (the first of M2c-6b's
--     three prerequisites to switching cancellation after download on; the other two are pgTAP 034's todo() cases).
--
-- M2c-6a review, round 7 (round 6's verifiers; ADR-0014 « M2c-6a review fixes », round 7; COMPLIANCE OQ-80 (n)):
--   * private.refund_transfer_follow (the founder's decision on round 6's N1, option (b)): while the refund's transfer
--     is in a downloaded or sent file, `executed` is also accepted from a line carrying neither an end-to-end id nor a
--     PmtInfId when that transfer re-issues none (`replaces_transfer_id` null — always so while the switch is off): M2b's
--     behaviour for a CSV feed without the reference column (a CSV never carries a PmtInfId). A line naming another
--     end-to-end id or another PmtInf (of the same file — the sweep's — or another) stays refused, and so does a
--     reference-less line for a re-issue (it may be the old file's execution). The `reissue_in_downloaded_file` hint
--     names the file and what the line carries; it says the refund would be paid a second time only where that is so
--     (a re-issue, the switch on: linked before its file is cancelled);
--   * the refusal hints that said a downloaded file's transfers wait for their debits « read from the statement »
--     (cancel_transfer_file, the four cancellation commands, cancel_remittance_run) say they wait for them to be booked
--     from it — a refund's once linked, a payout's or the sweep's not yet (M2c-6b books them).

