-- The first day a file generated at p_at can ask the paying account to execute (§11, L133-9 « jour convenu »): today
-- when it is a business day and the account's cut-off (Paris time, « Facturation ») has not passed, else the next
-- business day (no cut-off recorded: never today), as private.execution_date_refusal at approval.
create or replace function private.transfer_earliest_execution_date(p_bank_account_id uuid,
                                                                    p_at timestamptz default clock_timestamp())
returns date
language plpgsql
stable
set search_path = ''
as $$
declare
  v_today date := (p_at at time zone 'Europe/Paris')::date;
  v_cutoff text;
begin
  select s.bank_cutoff ->> p_bank_account_id::text into v_cutoff
  from public.bank_account b join public.servicer_billing_settings s on s.organization_id = b.organization_id
  where b.id = p_bank_account_id;
  if private.is_business_day(v_today) and v_cutoff is not null
     and (p_at at time zone 'Europe/Paris')::time < v_cutoff::time then
    return v_today;
  end if;
  return private.next_business_day(v_today);
end;
$$;

-- Our own debit of a transfer on an imported statement of its account: a line carrying its end-to-end id. Keyed by
-- the id alone — a subquery that cannot be pulled up, the account and the direction checked on the lines found
-- (ARCHITECTURE §4) — so bank_transaction_end_to_end_idx is the one index that can serve it, whatever the statistics.
create or replace function private.transfer_own_debit_seen(p_bank_account_id uuid, p_end_to_end_id text)
returns boolean
language sql
stable
set search_path = ''
set enable_seqscan = off
as $$
  select count(*) > 0 from (select x.bank_account_id, x.direction from public.bank_transaction x
                            where x.end_to_end_id = p_end_to_end_id offset 0) x
  where x.bank_account_id = p_bank_account_id and x.direction = 'debit';
$$;

-- The bank ignored BtchBookg and debited a PmtInf of our file as one line (camt.053 Btch/PmtInfId, no end-to-end id):
-- it books that PmtInf's transfers only when its amount equals the sum of those not cancelled and not debited on
-- their own (design §12's batch rule; review pain001#3). Any other batch debit explains none of them (M2c-6b, ops).
-- One sum per PmtInf, and only when such a line exists (keyed probes: (account, PmtInfId), then the PmtInf's items).
-- Review round 3: (E3, N4, N5) a transfer of the PmtInf whose return is seen was paid in the batch — it stays in the sum
-- once cancelled; (E1) only the transfers the file holds count (not those a file superseded before download passed on).
create or replace function private.pmt_inf_batch_seen(p_file_id uuid, p_pmt_inf_id text)
returns boolean
language plpgsql
stable
set search_path = ''
set enable_seqscan = off
as $$
declare
  v_account uuid;
  v_sum bigint;
begin
  select f.debtor_bank_account_id into v_account from public.transfer_file f where f.id = p_file_id;
  if not exists (select 1 from public.bank_transaction x
                 where x.bank_account_id = v_account and x.payment_info_id = p_pmt_inf_id and x.direction = 'debit'
                   and x.end_to_end_id is null) then
    return false;
  end if;
  select coalesce(sum(t.amount_minor), 0) into v_sum
  from public.transfer_file_item i
  cross join lateral (select t.amount_minor, t.end_to_end_id, t.status, t.transfer_file_id from public.bank_transfer t
                      where t.id = i.transfer_id offset 0) t
  where i.pmt_inf_id = p_pmt_inf_id and i.file_id = p_file_id and t.transfer_file_id = p_file_id
    and (t.status <> 'cancelled' or private.transfer_return_seen(i.transfer_id))
    and not private.transfer_own_debit_seen(v_account, t.end_to_end_id);
  return exists (select 1 from public.bank_transaction x
                 where x.bank_account_id = v_account and x.payment_info_id = p_pmt_inf_id and x.direction = 'debit'
                   and x.end_to_end_id is null and x.amount_minor = v_sum);
end;
$$;

-- A debit of this transfer is on an imported statement of its account: its end-to-end id, or a batch debit of its
-- PmtInf that books it (private.pmt_inf_batch_seen; M2c-6b books them; here it only stops counting it as in flight).
create or replace function private.transfer_debit_seen(p_transfer_id uuid)
returns boolean
language plpgsql
stable
set search_path = ''
set enable_seqscan = off
as $$
declare
  t public.bank_transfer;
  v_pmt_inf text;
begin
  -- keyed probes (ARCHITECTURE §4): the transfer by its key, then its account's debits by (account, our id) and, for a
  -- batch, by (account, PmtInfId)
  select * into t from public.bank_transfer where id = p_transfer_id;
  if private.transfer_own_debit_seen(t.debtor_bank_account_id, t.end_to_end_id) then
    return true;
  end if;
  if t.status = 'cancelled' or t.transfer_file_id is null then
    return false;
  end if;
  select i.pmt_inf_id into v_pmt_inf from public.transfer_file_item i
  where i.file_id = t.transfer_file_id and i.transfer_id = t.id;
  return v_pmt_inf is not null and private.pmt_inf_batch_seen(t.transfer_file_id, v_pmt_inf);
end;
$$;

-- The bank returned this transfer: a credit `return` on its account carrying its end-to-end id (review T1: evidence it
-- was not paid, with or without its debit).
create or replace function private.transfer_return_seen(p_transfer_id uuid)
returns boolean
language sql
stable
set search_path = ''
set enable_seqscan = off
as $$
  -- keyed by the transfer, then its id alone (as private.transfer_own_debit_seen): bank_transaction_return_e2e_idx
  select count(*) > 0 from public.bank_transfer t
  cross join lateral (select x.bank_account_id, x.direction, x.kind from public.bank_transaction x
                      where coalesce(x.original_end_to_end_id, x.end_to_end_id) = t.end_to_end_id offset 0) x
  where t.id = p_transfer_id and x.bank_account_id = t.debtor_bank_account_id and x.direction = 'credit'
    and x.kind = 'return';
$$;

-- Every business day from p_from to p_to is in an imported statement of the account (review T1: a statement that
-- covers the execution date and the next business day shows every debit the bank booked for it). Review round 2 (D1,
-- money#1, security#1): a day counts only once it is over — in a statement uploaded after that day (Paris), whose
-- period holds it; a CSV's period ends with its last booking, whatever the time it was exported, so a CSV never covers
-- its last booking day (a camt.053's period is the bank's own, FrToDt). Outside the seeded calendar: refused
-- (private.is_business_day raises). Review round 3 (E4, N6): a camt.053 counts by when the bank produced it, not when it
-- was uploaded — a day only in a statement created (Stmt/CreDtTm, Paris) after that day, whenever it is uploaded (a
-- statement exported during the day and uploaded the next one proves nothing of that day); none whose creation time is
-- not known (imported before it was kept). A CSV keeps round 2's rule. Review round 4 (G3, H8): a camt.053 counts a
-- day only within one of its sections' own whole days (`covers_from` … `covers_to`: what the parser reads of FrToDt in
-- Paris time — never a day between two sections of the file, the part-day at either end of a period, nor a section
-- without them), and never a window across a break in the balances: two sections of the account's camt.053
-- statements in the window, the later one opening (opening_minor) with other than what the one ending last before it
-- closed with (« relevé manquant », as the `opening_differs` and `statement_gap` warnings) — the movements between
-- them are on no statement (OQ-80 (f)). Keyed: the account's statements by (account, to_date), then their sections.
create or replace function private.statement_covers(p_bank_account_id uuid, p_from date, p_to date)
returns boolean
language plpgsql
stable
set search_path = ''
set enable_seqscan = off
as $$
declare
  d date;
begin
  if p_from is null or p_to is null or p_to < p_from then
    return false;
  end if;
  if exists (
       with c as materialized (   -- the camt.053 sections of the account that reach into the window
         select (v ->> 'from_date')::date as from_date, (v ->> 'to_date')::date as to_date,
                (v ->> 'opening_minor')::bigint as opening, (v ->> 'closing_minor')::bigint as closing
         from public.bank_statement s
         cross join lateral jsonb_array_elements(case jsonb_typeof(s.sections) when 'array' then s.sections end) v
         where s.bank_account_id = p_bank_account_id and s.status = 'imported' and s.format = 'camt053'
           and s.to_date >= p_from and s.from_date <= p_to
           and (v ->> 'to_date')::date >= p_from and (v ->> 'from_date')::date <= p_to)
       select 1 from c x
       join c p on p.to_date = (select max(y.to_date) from c y where y.to_date < x.from_date)
       where x.opening <> p.closing) then
    return false;
  end if;
  for d in select g::date from generate_series(p_from, p_to, interval '1 day') g loop
    if private.is_business_day(d) and not exists (
         select 1 from public.bank_statement s
         where s.bank_account_id = p_bank_account_id and s.status = 'imported' and s.to_date >= d
           and s.from_date <= d
           and case when s.format = 'csv' then (s.uploaded_at at time zone 'Europe/Paris')::date > d and s.to_date > d
                    else coalesce((s.bank_created_at at time zone 'Europe/Paris')::date > d, false)
                         and exists (select 1
                                     from jsonb_array_elements(case jsonb_typeof(s.sections) when 'array'
                                                                    then s.sections end) v
                                     where (v ->> 'covers_from')::date <= d and (v ->> 'covers_to')::date >= d) end) then
      return false;
    end if;
  end loop;
  return true;
end;
$$;

-- The bank executed something of this file (review round 2, D2): a debit carrying one of its PmtInfIds (a batch, whatever
-- its amount), a debit carrying one of its transfers' end-to-end ids, or the return of one of them. Keyed probes: one per
-- PmtInf by (account, PmtInfId), then each transfer's by its id (ARCHITECTURE §4); it stops at the first found. Review
-- round 3 (E1, N3): only the ids of the transfers the file holds (its own PmtInfIds are its own by their number) — never
-- a transfer it passed on, nor a cancelled file's: those are re-issued under fresh ids.
create or replace function private.transfer_file_executed(p_file_id uuid)
returns boolean
language sql
stable
set search_path = ''
set enable_seqscan = off
as $$
  select exists (select 1 from (select distinct i.pmt_inf_id from public.transfer_file_item i where i.file_id = f.id) p
                 where exists (select 1 from public.bank_transaction x
                               where x.bank_account_id = f.debtor_bank_account_id and x.payment_info_id = p.pmt_inf_id
                                 and x.direction = 'debit'))
      or exists (select 1 from public.transfer_file_item i
                 cross join lateral (select o.id, o.end_to_end_id, o.transfer_file_id from public.bank_transfer o
                                     where o.id = i.transfer_id offset 0) o
                 where i.file_id = f.id and o.transfer_file_id = f.id
                   and (private.transfer_own_debit_seen(f.debtor_bank_account_id, o.end_to_end_id)
                        or private.transfer_return_seen(o.id)))
  from public.transfer_file f where f.id = p_file_id;
$$;

-- Whether some of p_amounts, one alone or several together, add up to exactly p_target (review round 2, D3: another
-- open transfer of a batch-booked PmtInf could stand in for this one). The partial sums below the target, kept as a
-- set; past 10,000 of them it answers true (« cannot be ruled out »: the caller refuses rather than guesses).
create or replace function private.amounts_make_up(p_amounts bigint[], p_target bigint)
returns boolean
language plpgsql
immutable
parallel safe
set search_path = ''
as $$
declare
  v_sums bigint[] := array[0::bigint];
  a bigint;
begin
  foreach a in array coalesce(p_amounts, '{}'::bigint[]) loop
    continue when a is null or a <= 0 or a > p_target;
    if p_target - a = any (v_sums) then
      return true;
    end if;
    v_sums := array(select distinct s
                    from unnest(v_sums || array(select x + a from unnest(v_sums) x where x + a < p_target)) s);
    if cardinality(v_sums) > 10000 then
      return true;
    end if;
  end loop;
  return false;
end;
$$;

-- Whether a batch line (no end-to-end id) of this PmtInf of a file can contain this transfer (review round 3, E2, N1):
-- its amount is the transfer's, alone or with other transfers of the PmtInf not debited on their own
-- (private.amounts_make_up, which answers « can » past its bound) — pmt_inf_batch_seen's rule, widened to any part of
-- the PmtInf, since a cancelled file the bank executes late may be executed in part. Keyed: (account, PmtInfId), then
-- the PmtInf's items. Review round 4 (G1): p_after, when given, reads only the lines booked after that day (those of a
-- live file after the window that proved the transfer left out).
create or replace function private.batch_debit_may_hold(p_file_id uuid, p_pmt_inf_id text, p_transfer_id uuid,
                                                        p_after date default null)
returns boolean
language plpgsql
stable
set search_path = ''
set enable_seqscan = off
as $$
declare
  v_account uuid;
  v_amount bigint;
  v_others bigint[];
begin
  select f.debtor_bank_account_id into v_account from public.transfer_file f where f.id = p_file_id;
  if not exists (select 1 from public.bank_transaction x
                 where x.bank_account_id = v_account and x.payment_info_id = p_pmt_inf_id and x.direction = 'debit'
                   and x.end_to_end_id is null and (p_after is null or x.booking_date > p_after)) then
    return false;
  end if;
  select t.amount_minor into v_amount from public.bank_transfer t where t.id = p_transfer_id;
  select coalesce(array_agg(o.amount_minor order by o.amount_minor desc), '{}') into v_others
  from public.transfer_file_item i
  cross join lateral (select o.amount_minor, o.end_to_end_id from public.bank_transfer o
                      where o.id = i.transfer_id offset 0) o
  where i.file_id = p_file_id and i.pmt_inf_id = p_pmt_inf_id and i.transfer_id <> p_transfer_id
    and not private.transfer_own_debit_seen(v_account, o.end_to_end_id);
  return exists (select 1 from public.bank_transaction x
                 where x.bank_account_id = v_account and x.payment_info_id = p_pmt_inf_id and x.direction = 'debit'
                   and x.end_to_end_id is null and (p_after is null or x.booking_date > p_after)
                   and (x.amount_minor = v_amount
                        or (x.amount_minor > v_amount and private.amounts_make_up(v_others, x.amount_minor - v_amount))));
end;
$$;

-- The transfer has left the account already (review round 3, E2, N1, N2): it, or a transfer it re-issues (its replaces
-- chain), shows a debit of its own end-to-end id — but for the transfer's own execution out of the downloaded file it
-- is in now —, or a batch line of a PmtInf that held it in a downloaded file cancelled since can contain it
-- (private.batch_debit_may_hold); a transfer whose return is seen left nothing. Used to hold it out of every file
-- (`already_debited`), to alert it (`transfer_already_debited`), to refuse cancelling its run or refund, and for the
-- cancelled sweeps. Keyed: the chain by id, each one's debits by its id, its items by transfer (ARCHITECTURE §4).
-- Review round 4 (G1, H1a, H1b): or, cancelled alone out of a downloaded file still live (the bank refused it: the
-- batch line of its PmtInf left it out), a batch line of that PmtInf booked after its cancellation's window (its
-- execution date's next business day: the days whose statements proved it left out) that can contain it — the bank
-- executing it late after all.
create or replace function private.transfer_debited_before(p_transfer_id uuid)
returns boolean
language plpgsql
stable
set search_path = ''
set enable_seqscan = off
as $$
declare
  t public.bank_transfer;
  v_live uuid;   -- the downloaded file the transfer is in now (its own debit there is its execution)
  v_depth integer := 0;
begin
  select * into t from public.bank_transfer where id = p_transfer_id;
  if t.status = 'in_file' then
    select f.id into v_live from public.transfer_file f where f.id = t.transfer_file_id and f.download_count > 0;
  end if;
  while t.id is not null and v_depth < 1000 loop
    if (v_depth > 0 or v_live is null)
       and private.transfer_own_debit_seen(t.debtor_bank_account_id, t.end_to_end_id)
       and not private.transfer_return_seen(t.id) then
      return true;
    end if;
    if exists (select 1 from public.transfer_file_item i
               cross join lateral (select f.download_count, f.status from public.transfer_file f
                                   where f.id = i.file_id offset 0) f
               where i.transfer_id = t.id and f.download_count > 0
                 and ((f.status in ('superseded', 'rejected')
                       and private.batch_debit_may_hold(i.file_id, i.pmt_inf_id, t.id))
                      or (t.status = 'cancelled' and f.status in ('downloaded', 'sent')
                          and private.batch_debit_may_hold(i.file_id, i.pmt_inf_id, t.id,
                                                           private.next_business_day(i.execution_date)))))
       and not private.transfer_return_seen(t.id) then
      return true;
    end if;
    exit when t.replaces_transfer_id is null;
    select * into t from public.bank_transfer where id = t.replaces_transfer_id;
    v_depth := v_depth + 1;
  end loop;
  return false;
end;
$$;

