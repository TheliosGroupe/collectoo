  size_bytes bigint check (size_bytes > 0),
  storage_path text unique check (length(storage_path) between 1 and 500),
  xsd_validated boolean,
  renderer_version text check (length(renderer_version) between 1 and 40),
  generated_at timestamptz,
  error text check (length(error) <= 2000),
  download_count integer not null default 0 check (download_count >= 0),
  first_downloaded_by uuid references public.app_user (id),
