           'to_file_count', (select count(*) from todo x where x.debtor_bank_account_id = a.id),
           'eligible_count', (select count(*) from todo x where x.debtor_bank_account_id = a.id
                                and (x.hold is null or x.hold = 'late_reason_required')),
